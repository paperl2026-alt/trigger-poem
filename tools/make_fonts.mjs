// Keeps only the font chunks whose unicode-range covers characters the game actually uses.
// Writes src/fonts/fonts.css + src/fonts/files/*.woff2.  usage: node tools/make_fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = ['node_modules/@fontsource/zcool-qingke-huangyou/index.css', 'node_modules/@fontsource/dela-gothic-one/index.css'];

// every character in the source + full printable ASCII + some UI punctuation
const used = new Set();
for (let c = 0x20; c < 0x7f; c++) used.add(c);
for (const ch of '…—–·「」『』！？：，。、♥★☆▶◀◆●○✕×÷%％～ー') used.add(ch.codePointAt(0));
const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) { if (f.name !== 'fonts') walk(p); } else if (/\.(js|css|html)$/.test(f.name)) for (const ch of fs.readFileSync(p, 'utf8')) used.add(ch.codePointAt(0)); } };
walk(path.join(root, 'src'));
for (const ch of fs.readFileSync(path.join(root, 'index.html'), 'utf8')) used.add(ch.codePointAt(0));

const parseRange = (s) => s.split(',').map((r) => r.trim().replace(/^U\+/i, '')).map((r) => {
  if (r.includes('?')) return [parseInt(r.replace(/\?/g, '0'), 16), parseInt(r.replace(/\?/g, 'f'), 16)];
  const [a, b] = r.split('-'); return [parseInt(a, 16), parseInt(b || a, 16)];
});

const outDir = path.join(root, 'src/fonts/files');
fs.rmSync(path.join(root, 'src/fonts'), { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });
let css = '/* generated by tools/make_fonts.mjs: only the chunks this game needs */\n';
let n = 0, bytes = 0;
for (const src of SOURCES) {
  const text = fs.readFileSync(path.join(root, src), 'utf8');
  for (const m of text.matchAll(/@font-face\s*{([^}]*)}/g)) {
    const body = m[1];
    const fam = /font-family:\s*'([^']+)'/.exec(body)[1];
    const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)[1];
    const rangeStr = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
    const ranges = rangeStr ? parseRange(rangeStr) : [[0, 0x10ffff]];
    let hit = false;
    for (const cp of used) { if (ranges.some(([a, b]) => cp >= a && cp <= b)) { hit = true; break; } }
    if (!hit) continue;
    fs.copyFileSync(path.join(root, path.dirname(src), 'files', file), path.join(outDir, file));
    bytes += fs.statSync(path.join(outDir, file)).size;
    css += `@font-face{font-family:'${fam}';font-style:normal;font-display:swap;font-weight:400;src:url(./files/${file}) format('woff2');${rangeStr ? `unicode-range:${rangeStr};` : ''}}\n`;
    n++;
  }
}
fs.writeFileSync(path.join(root, 'src/fonts/fonts.css'), css);
console.log(`fonts: ${n} chunks, ${(bytes / 1024).toFixed(0)} KB, ${used.size} characters covered`);
